#!/bin/bash
set -e

echo "🚀 Deploy script starting..."

# Patch schema provider based on DATABASE_URL
if [[ "$DATABASE_URL" == postgres* ]] || [[ "$DATABASE_URL" == postgresql* ]]; then
  echo "📦 PostgreSQL detected — patching schema provider..."
  sed -i 's/provider = env("DATABASE_PROVIDER")/provider = "postgresql"/' prisma/schema.prisma
  sed -i 's/provider = "sqlite"/provider = "postgresql"/' prisma/schema.prisma
  # Also update migration_lock.toml
  echo -e '# Please do not edit this file manually\n# It should be added in your version-control system (i.e. Git)\nprovider = "postgresql"' > prisma/migrations/migration_lock.toml
  echo "✅ Schema patched to postgresql"
  # Use db push for full schema sync (safe for additive changes)
  npx prisma db push --accept-data-loss
else
  echo "📦 SQLite detected — skipping schema patch"
fi

echo "✅ Database ready"

# Validate required env vars
if [ -z "$VAPID_PUBLIC_KEY" ] || [ -z "$VAPID_PRIVATE_KEY" ]; then
  echo "⚠️  VAPID_PUBLIC_KEY / VAPID_PRIVATE_KEY not set — web push disabled"
  echo "   Set these in Railway: VAPID_PUBLIC_KEY, VAPID_PRIVATE_KEY, VAPID_SUBJECT"
fi

echo "🚀 Starting server..."
node dist/index.js
